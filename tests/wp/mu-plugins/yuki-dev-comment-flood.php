<?php
/**
 * Plugin Name: Yuki 开发环境 · 关掉评论频率限制
 * Description: 本地验证环境的设施：关闭 WordPress 内核的评论频率限制（15 秒内同一 IP 的第二条评论会被 429 挡掉）。这是本地环境的东西，不是主题的一部分。**这是本目录里唯一一处刻意改变产品行为的地方**，原因见下。
 *
 * @package Yuki\DevHarness
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

/*
 * 为什么要关掉它。
 *
 * 内核的频率限制（wp_throttle_comment_flood）按「IP + 邮箱」在 15 秒内去重，而这个
 * 15 秒是**硬编码**的，没有筛子可调（WP 7.1.3，wp-includes/comment.php:2315）。
 * 本地环境里每个请求都来自 127.0.0.1，所以它区分不了「测试套件」和「攻击者」——
 * 只会把正常跑测试的第二条评论判成刷屏。
 *
 * 更要紧的是它会造成**假通过**：工单 02 要验「页面渲染到提交不足 3 秒就不该产生评论」，
 * 而这样的提交必然落在 15 秒窗口里，会被频率限制先挡掉。测试看到「没有产生评论」，
 * 却是在验错的原因。关掉它，02 的断言才真的在验主题自己那道时间戳。
 *
 * 受影响的是内核行为，不是主题行为：没有任何一条验收标准是关于频率限制的，
 * 主题自己的防垃圾（蜜罐 + 时间戳令牌）在工单 02 里另外验。
 *
 * 优先级 20 压在 wp_throttle_comment_flood（优先级 10）之后，把它的判断覆盖掉；
 * 不用 remove_filter 是因为那样依赖 default-filters.php 的加载时序。
 */
add_filter( 'comment_flood_filter', '__return_false', 20 );
